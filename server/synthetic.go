// seedSynthetic fills a project with forecast.Synthetic(n, seed): the plan the engine scale tests
// use (about 3.4 links per issue, a fifth done, a few cycles), as real issues and links.
func seedSynthetic(ctx context.Context, tx pgx.Tx, projectID string, n int, seed uint32) error {
	plan := forecast.Synthetic(n, seed)
	statuses := map[string]string{}
	rows, err := tx.Query(ctx, `SELECT DISTINCT ON (category) category, id FROM statuses WHERE project_id = $1 ORDER BY category, position`, projectID)
	if err != nil {
		return err
	}
	for rows.Next() {
		var cat, id string
		if err := rows.Scan(&cat, &id); err != nil {
			return err
		}
		statuses[cat] = id
	}
	if err := rows.Err(); err != nil {
		return err
	}
	var base int
	if err := tx.QueryRow(ctx, `SELECT coalesce(max(number), 0) FROM issues WHERE project_id = $1`, projectID).Scan(&base); err != nil {
		return err
	}
	ids := make([]string, n)
	issueRows := make([][]any, 0, n)
	for i, node := range plan.Nodes {
		ids[i] = newUUID()
		var due any
		if d, ok := plan.DueDates[node.ID]; ok {
			due = d
		}
		issueRows = append(issueRows, []any{ids[i], projectID, base + i + 1, plan.Types[node.ID], "Synthetic issue " + node.ID[1:],
			statuses[node.State], "medium", node.Estimate, due, float64(base + i + 1)})
	}
	if _, err := tx.CopyFrom(ctx, pgx.Identifier{"issues"},
		[]string{"id", "project_id", "number", "type", "title", "status_id", "priority", "estimate", "due_date", "rank"}, pgx.CopyFromRows(issueRows)); err != nil {
		return err
	}
	var links [][]any
	for i, node := range plan.Nodes {
		for _, dep := range node.DependsOn {
			j, _ := strconv.Atoi(dep[1:])
			links = append(links, []any{ids[j], ids[i]})
		}
	}
	_, err = tx.CopyFrom(ctx, pgx.Identifier{"issue_links"}, []string{"blocker_id", "blocked_id"}, pgx.CopyFromRows(links))
	return err
}

// runSynthetic implements `graphly synthetic`: create a large generated project for load and UI
// testing. It never touches existing projects.
func runSynthetic(ctx context.Context, pool *pgxpool.Pool, args []string) error {
	fs := flag.NewFlagSet("synthetic", flag.ContinueOnError)
	ws := fs.String("workspace", "", "workspace id to create the project in (required)")
	n := fs.Int("issues", 5000, "number of issues")
	seed := fs.Uint("seed", 1, "generator seed")
	key := fs.String("key", "SYN", "project key")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if !validID(*ws) || *n < 1 || *n > 100000 {
		return fmt.Errorf("usage: graphly synthetic -workspace <id> [-issues 5000] [-seed 1] [-key SYN]")
	}
	start := time.Now()
	var p Project
	err := pgx.BeginFunc(ctx, pool, func(tx pgx.Tx) error {
		var err error
		if p, err = createProjectTx(ctx, tx, *ws, *key, fmt.Sprintf("Synthetic (%d issues)", *n), "Generated by graphly synthetic.", false, nil); err != nil {
			return err
		}
		return seedSynthetic(ctx, tx, p.ID, *n, uint32(*seed))
	})
	if err != nil {
		return err
	}
	fmt.Printf("created project %s (%s) with %d issues in %v\n", p.ID, p.Key, *n, time.Since(start).Round(time.Millisecond))
	return nil
}

// newUUID returns a random (version 4) UUID.
func newUUID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:])
}
